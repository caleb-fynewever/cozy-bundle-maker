export const LEVELS = [
  { level: 1, name: "Wanderer", xp: 0 },
  { level: 2, name: "Explorer", xp: 250 },
  { level: 3, name: "Local", xp: 700 },
  { level: 4, name: "Adventurer", xp: 1500 },
  { level: 5, name: "wego Legend", xp: 3000 },
];

export function levelFor(xp: number) {
  let current = LEVELS[0]!;
  for (const entry of LEVELS) if (xp >= entry.xp) current = entry;
  const next = LEVELS.find((l) => l.xp > xp);
  const span = next ? next.xp - current.xp : 1;
  const progress = next ? Math.min(1, (xp - current.xp) / span) : 1;
  return { ...current, next, progress };
}
